/**
 * Generates src/embed/inline-icons.js containing all SVG icon data as an
 * inline JavaScript map.  Icons larger than 20 KB are excluded to keep the
 * widget bundle small.
 *
 * Run: node scripts/generate-inline-icons.js
 */
const fs = require('fs');
const path = require('path');

const ICON_DIR = path.join(__dirname, '..', 'public', 'data_type_icons');
const OUT_FILE = path.join(__dirname, '..', 'src', 'embed', 'inline-icons.js');
const MAX_BYTES = 20_000;

const files = fs.readdirSync(ICON_DIR)
  .filter(f => f.endsWith('.svg'))
  .sort();

const map = {};
const skipped = [];

for (const f of files) {
  const fullPath = path.join(ICON_DIR, f);
  const stat = fs.statSync(fullPath);
  if (stat.size > MAX_BYTES) {
    skipped.push(`${f} (${(stat.size / 1024).toFixed(0)} KB)`);
    continue;
  }
  const code = f.replace('.svg', '');
  map[code] = fs.readFileSync(fullPath, 'utf-8');
}

// Build output as a JSON-based module so we don't need tricky escaping.
const jsonMap = JSON.stringify(map, null, 2);
const output = `// Auto-generated by scripts/generate-inline-icons.js — do not edit.
// Embeds ${Object.keys(map).length} SVG icons inline for widget builds.
// Excluded (>${MAX_BYTES / 1000} KB): ${skipped.join(', ') || 'none'}

const INLINE_ICONS = ${jsonMap};

export default INLINE_ICONS;
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, output, 'utf-8');

console.log(`✓ Generated ${OUT_FILE}`);
console.log(`  ${Object.keys(map).length} icons embedded, ${skipped.length} skipped`);
